def tab_exec(d, h, f, cred, a, b, label, al):
    k = kpis(h, a, b)
    kp = kpis(h, a - WEEKS_PER_YEAR, b - WEEKS_PER_YEAR) if a - WEEKS_PER_YEAR >= 1 else None
    ct = credit_table(h, a, b, cred)
    kpi_cards(k, kp, growth_yoy(h, a, b), ct, a, b)
    # headline insights
    meta = d["meta"]
    last = int(meta["last_week_id"])
    ly_weeks = range(last - 52 + 1, last - 52 + 27)                       # same 26 weeks one year before the forecast
    fdem = f.demand_forecast.sum()
    ly_dem = h[h.week_id.isin(ly_weeks)].demand_est.sum()
    cur13 = d["hist"][d["hist"].week_id > last - 13]
    pc = cur13.groupby("product_name").agg(stock=("stock_units", "mean"), dem=("demand_est", "mean"), cogs=("unit_cogs", "last"))
    over = pc[pc.stock / pc.dem > DEFAULT_THRESHOLDS["cover_max"]]
    tied = ((over.stock - DEFAULT_THRESHOLDS["cover_max"] * over.dem) * over.cogs).sum()
    st.markdown("##### What the numbers say")
    st.markdown(
        f"- **{pct(k['lost_share'])} of demand went unserved** in {label.lower()}: about **{money(k['lost_revenue'])}** of revenue lost to stock-outs and stock caps "
        f"(service level {pct(k['service_level'])}).\n"
        f"- **{len(over)} products hold more than {DEFAULT_THRESHOLDS['cover_max']:.0f} weeks of stock**, tying up roughly **{money(tied)}** of excess inventory at cost "
        f"while the lean products run out.\n"
        f"- **Next 26 weeks:** forecast demand {num(fdem)} units, {('%+.1f%%' % (100 * (fdem / ly_dem - 1))) if ly_dem else 'n/a'} vs the same weeks last year, "
        f"entering the seasonal peak; at historical stock levels about **{pct(f.exp_lost_revenue.sum() / f.exp_revenue.sum())}** of that demand would again be unserved.\n"
        f"- **Margins are stable** ({pct(k['gpm'])} gross); the opportunity is volume and stock, not price.")
    basis = st.radio("Forecast basis", ["At historical stock levels (comparable to actuals)", "Unconstrained demand potential"], horizontal=True, key="exec_basis")
    c1, c2 = st.columns(2)
    hq = h.groupby("pq").agg(revenue=("revenue", "sum"), gp=("gross_profit", "sum"), op=("operating_profit", "sum"), ws=("week_start", "min")).reset_index().sort_values("ws")
    fq = f.groupby("pq").agg(exp_sales=("exp_sales_revenue", "sum"), pot=("exp_revenue", "sum"), ws=("week_start", "min")).reset_index().sort_values("ws")
    fig = go.Figure()
    fig.add_bar(x=hq.pq, y=hq.revenue, name="Actual revenue", marker_color=BLUE, hovertemplate="%{y:$,.0f}")
    ycol, yname = ("exp_sales", "Forecast revenue (at historical stock)") if basis.startswith("At") else ("pot", "Forecast revenue potential (unconstrained)")
    fig.add_bar(x=fq.pq, y=fq[ycol], name=yname, marker_color=AQUA, hovertemplate="%{y:$,.0f}")
    if basis.startswith("At"):
        fig.add_scatter(x=fq.pq, y=fq.pot, mode="markers", name="Demand potential", marker=dict(color=ORANGE, size=10, line=dict(color=SURFACE, width=2)), hovertemplate="%{y:$,.0f}")
    fig.update_layout(barmode="group", bargap=0.25)
    fig.update_yaxes(tickprefix="$", tickformat="~s")
    with c1:
        show(style(fig, 360, "Revenue by 13-week quarter (Y = data year) and 26-week forecast"), "exec_rev")
    gm = h.groupby("pq").agg(rev=("revenue", "sum"), gp=("gross_profit", "sum"), op=("operating_profit", "sum"), ws=("week_start", "min")).reset_index().sort_values("ws")
    fig = go.Figure()
    fig.add_scatter(x=gm.pq, y=gm.gp / gm.rev, name="Gross margin", mode="lines+markers", line=dict(color=BLUE, width=2), marker=dict(size=7), hovertemplate="%{y:.1%}")
    fig.add_scatter(x=gm.pq, y=gm.op / gm.rev, name="Operating margin", mode="lines+markers", line=dict(color=ORANGE, width=2), marker=dict(size=7), hovertemplate="%{y:.1%}")
    fig.update_yaxes(tickformat=".0%", rangemode="tozero")
    with c2:
        show(style(fig, 360, "Margins by quarter"), "exec_margin")
    c1, c2 = st.columns([3, 2])
    dh = h[h.week_id > b - 104].groupby(["week_id", "week_start"]).agg(sales=("units", "sum"), dem=("demand_est", "sum")).reset_index()
    ff = f.groupby(["week_id", "week_start"]).agg(p50=("demand_forecast", "sum"), p10=("p10", "sum"), p90=("p90", "sum")).reset_index()
    fig = go.Figure()
    fig.add_scatter(x=dh.week_start, y=dh.sales, name="Observed sales", line=dict(color=BLUE, width=2), hovertemplate="%{y:,.0f}")
    fig.add_scatter(x=dh.week_start, y=dh.dem, name="Reconstructed demand", line=dict(color=ORANGE, width=2), hovertemplate="%{y:,.0f}")
    fig.add_scatter(x=ff.week_start, y=ff.p90, line=dict(width=0), showlegend=False, hoverinfo="skip")
    fig.add_scatter(x=ff.week_start, y=ff.p10, line=dict(width=0), fill="tonexty", fillcolor="rgba(27,175,122,0.22)", name="Forecast P10-P90", hoverinfo="skip")
    fig.add_scatter(x=ff.week_start, y=ff.p50, name="Forecast demand (P50)", line=dict(color=AQUA, width=2.5), hovertemplate="%{y:,.0f}")
    fig.update_yaxes(tickformat="~s")
    with c1:
        show(style(fig, 380, "Weekly units, all selected products: observed sales vs demand vs forecast"), "exec_demand")
    with c2:
        st.markdown("##### Top alerts")
        alerts_table(al, 6, key="exec_alerts", compact=True)
        st.caption("Full list and thresholds in the Alerts tab.")


def tab_financial(d, h, f, cred, a, b, label):
    k = kpis(h, a, b)
    grain = st.radio("Granularity", ["13-week quarter", "Calendar month (by week start)"], horizontal=True, key="fin_grain")
    key = "pq" if grain.startswith("13") else "ym"
    g = h.groupby(key).agg(revenue=("revenue", "sum"), gp=("gross_profit", "sum"), op=("operating_profit", "sum"), cogs=("cogs", "sum"), ws=("week_start", "min")).reset_index().sort_values("ws")
