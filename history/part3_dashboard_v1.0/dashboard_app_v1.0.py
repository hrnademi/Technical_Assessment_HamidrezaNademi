    fig = go.Figure()
    fig.add_bar(x=g[key], y=g.revenue, name="Revenue", marker_color=BLUE, hovertemplate="%{y:$,.0f}")
    fig.add_bar(x=g[key], y=g.gp, name="Gross profit", marker_color=ORANGE, hovertemplate="%{y:$,.0f}")
